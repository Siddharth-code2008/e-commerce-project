let cart = [];
let cost_price = 0;
const cost = document.querySelector(".cost");


const cart_div = document.querySelector(".cart_div");

for(let product of products){
    let cart_product = JSON.parse(localStorage.getItem(product.name));
    let cart_product_name = cart_product;
    

    

    if(product.name == cart_product_name){

        
        let product_div = document.createElement("div");
        product_div.classList.add("product_div");
        cart_div.appendChild(product_div);

        let product_image = document.createElement("img");
        product_image.classList.add("product_image");
        product_image.src = product.src ;
        product_div.appendChild(product_image);

        
        let product_name = document.createElement("h2");
        product_name.classList.add("product_name");
        product_name.innerText = product.name ;
        product_div.appendChild(product_name);

        let product_price = document.createElement("div");
        product_price.classList.add("product_price");
        product_price.innerText = product.price ;
        product_div.appendChild(product_price);

        let product_remove = document.createElement("button");
        product_remove.classList.add("product_remove");
        product_remove.innerText = "remove";
        product_div.appendChild(product_remove);
        

        const total = document.querySelector(".total");

        let order_div = document.createElement("div");
        order_div.classList.add("order_div");
        total.appendChild(order_div);

        let order_name = document.createElement("p");
        order_name.classList.add("order_name");
        order_name.innerText = product.name;
        order_div.appendChild(order_name);

        let order_price = document.createElement("p");
        order_price.classList.add("order_price");
        order_price.innerText = product.price;
        order_div.appendChild(order_price);


        cost_price = Number(cost_price) + Number(product.price);
        cost.innerText = cost_price;


        const place_order =  document.querySelector(".place_order");

        place_order.addEventListener("click", () => {
            localStorage.removeItem(cart_product_name);
            order_div.remove();
            product_div.remove();
            alert("thank you for order")            
            
        });


        product_remove.addEventListener("click", () => {
            order_div.remove();
            product_div.remove();
            cost_price = cost_price - Number(product.price)
            cost.innerText = cost_price;
            localStorage.removeItem(cart_product_name);

        })
        
    }
}









